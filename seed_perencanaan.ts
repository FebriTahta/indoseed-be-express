async function main() {
  console.log('Seeding perencanaan_produksi...');
  for (const item of seedData) {
    await prisma.perencanaanProduksi.upsert({
      where: { noPerencanaan: item.noPerencanaan },
      update: item,
      create: item
    });
  }
  const count = await prisma.perencanaanProduksi.count();
  console.log(`Successfully seeded! Total records: ${count}`);
}

main()
  .catch((e) => {
    console.error('Error seeding data:', e);
  })
  .finally(() => prisma.$disconnect());
